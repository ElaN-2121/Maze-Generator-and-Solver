def solve_maze(maze, start, end):

    visited = set()
    current_path = []
    dead_ends = []

    def is_safe_to_step(row, col):

        if row < 0 or row >= len(maze): return False
        if col < 0 or col >= len(maze[0]): return False

        if maze[row][col] == 1: return False

        if (row, col) in visited: return False

        return True


    def explore(row, col):

        visited.add((row, col))
        current_path.append((row, col))

        if (row, col) == end:
            return True

        directions = [(-1, 0), (1, 0), (0, -1), (0, 1)]

        for move_row, move_col in directions:
            next_row = row + move_row
            next_col = col + move_col

            if is_safe_to_step(next_row, next_col):
                if explore(next_row, next_col) == True:
                    return True


        dead_ends.append((row, col))
        current_path.pop()

        return False

    if explore(start[0], start[1]):
        print("Path found!")
        return current_path, dead_ends
    else:
        print("No path exists.")
        return [], dead_ends

